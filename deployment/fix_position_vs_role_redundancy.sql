-- 0. 先确认需要修复的记录（SELECT 不修改数据）
SELECT id, tenant_id, username, name, position, role_name
FROM t_user
WHERE tenant_id = <你的租户ID>
  AND (
    -- 岗位等于角色名的所有情况
    position = role_name
    OR
    -- 或者已知「刘工人」+「跟单员」这一条
    (name = '刘工人' AND position = '跟单员')
  );

