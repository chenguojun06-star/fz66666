-- 背景：截图里第 4 行「刘工人」岗位被错填为「跟单员」，与角色权限重复。
--       后端 position 字段语义是"具体业务岗位"（如：缝纫一组组长），
--       区别于 roleName（系统权限分类），同名属于冗余数据。
--
-- 修复策略：
--   方案 A（推荐）：把 position 清空，让"角色权限"列承担称谓
--   方案 B：把 position 改成更具体的描述（如："生产部A组跟单员"）
--
-- 使用方法：
--   1. 先执行 SELECT 语句确认是哪些记录
--   2. 再执行 UPDATE（取消对应方案的注释）
--   3. 务必带上 tenant_id 限定，多租户场景下防止误改
